import CryptoKit
import Foundation

public enum ItemKind: String, Sendable, CaseIterable, Codable {
    case text, rich, url, file, image
}

public enum KindFilter: String, Sendable, CaseIterable {
    case all, text, image, file, url

    /// Kinds matched by this filter; nil = no restriction.
    var kinds: [ItemKind]? {
        switch self {
        case .all: nil
        case .text: [.text, .rich]
        case .image: [.image]
        case .file: [.file]
        case .url: [.url]
        }
    }
}

/// Pasteboard type written alongside our own copies so the watcher can skip them (I6).
/// Contract: PasteboardWriter ↔ CaptureDecision.
public enum SelfWriteMarker {
    public static let type = "local.clipvault.self"
}

public struct CapturedImage: Sendable, Equatable {
    public var data: Data          // bytes as stored (PNG preferred)
    public var uti: String
    public var width: Int
    public var height: Int
    public init(data: Data, uti: String, width: Int, height: Int) {
        self.data = data; self.uti = uti; self.width = width; self.height = height
    }
}

/// A plain-value copy of what the pasteboard held. Built by ClipPlatform, judged here.
public struct PasteboardSnapshot: Sendable, Equatable {
    public var changeCount: Int
    public var types: [String]
    public var string: String?
    public var rtf: Data?
    public var html: Data?
    public var fileURLs: [String] = []
    public var image: CapturedImage?

    public init(changeCount: Int, types: [String], string: String? = nil, rtf: Data? = nil, html: Data? = nil,
                fileURLs: [String] = [], image: CapturedImage? = nil) {
        self.changeCount = changeCount; self.types = types; self.string = string; self.rtf = rtf
        self.html = html; self.fileURLs = fileURLs; self.image = image
    }
}

public struct CaptureContext: Sendable, Equatable {
    public var frontmostBundleID: String?
    public var frontmostName: String?
    public var excludedBundleIDs: Set<String>
    public var lastSelfWriteChangeCount: Int?
    public init(frontmostBundleID: String?, frontmostName: String?, excludedBundleIDs: Set<String>, lastSelfWriteChangeCount: Int?) {
        self.frontmostBundleID = frontmostBundleID; self.frontmostName = frontmostName
        self.excludedBundleIDs = excludedBundleIDs; self.lastSelfWriteChangeCount = lastSelfWriteChangeCount
    }
}

/// Why something was not recorded. One terminal "not recorded" state, many causes (C10).
public enum SkipReason: String, Sendable, CaseIterable {
    case concealed, excludedApp, selfWrite, empty, unsupported, accessDenied, writeFailed
}

public struct Representation: Sendable, Equatable {
    public var uti: String
    public var data: Data
}

/// What will be stored for one capture.
public struct CaptureDraft: Sendable, Equatable {
    public var kind: ItemKind
    public var contentHash: String
    public var text: String?
    public var image: CapturedImage?
    public var representations: [Representation]
    public var byteSize: Int
}

public enum Preflight: Equatable, Sendable {
    case read
    case skip(SkipReason)
}

public enum Classification: Equatable, Sendable {
    case record(CaptureDraft)
    case skip(SkipReason)
    public var draft: CaptureDraft? { if case .record(let d) = self { d } else { nil } }
}

/// Pure capture rules. No I/O.
public enum CaptureDecision {
    /// Conventions from nspasteboard.org plus common password managers (Q2).
    public static let privacyTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Decides from type names only, before any content is read (I7).
    public static func preflight(types: [String], changeCount: Int, context: CaptureContext) -> Preflight {
        if types.contains(SelfWriteMarker.type) || context.lastSelfWriteChangeCount == changeCount { return .skip(.selfWrite) }
        if types.contains(where: privacyTypes.contains) { return .skip(.concealed) }
        if let app = context.frontmostBundleID, context.excludedBundleIDs.contains(app) { return .skip(.excludedApp) }
        if types.isEmpty { return .skip(.empty) }
        return .read
    }

    /// Precedence: file > rich > url > text > image (edge-cases E2–E5).
    public static func classify(_ s: PasteboardSnapshot) -> Classification {
        if !s.fileURLs.isEmpty {
            let paths = s.fileURLs.map { URL(string: $0)?.path ?? $0 }
            let text = paths.joined(separator: "\n")
            let reps = [Representation(uti: "public.file-url", data: Data(s.fileURLs.joined(separator: "\n").utf8))]
            return .record(draft(.file, text: text, image: nil, reps: reps))
        }
        if let raw = s.string {
            let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.isEmpty { return .skip(.empty) }
            var reps: [Representation] = []
            if let rtf = s.rtf { reps.append(Representation(uti: "public.rtf", data: rtf)) }
            if let html = s.html { reps.append(Representation(uti: "public.html", data: html)) }
            if !reps.isEmpty { return .record(draft(.rich, text: raw, image: nil, reps: reps)) }
            if isSingleURL(trimmed) { return .record(draft(.url, text: trimmed, image: nil, reps: [])) }
            return .record(draft(.text, text: raw, image: nil, reps: []))
        }
        if let image = s.image, !image.data.isEmpty {
            return .record(draft(.image, text: nil, image: image, reps: []))
        }
        return .skip(s.types.isEmpty ? .empty : .unsupported)
    }

    static func isSingleURL(_ s: String) -> Bool {
        guard !s.contains(where: \.isWhitespace), let url = URL(string: s), let scheme = url.scheme?.lowercased() else { return false }
        return ["http", "https", "ftp", "mailto"].contains(scheme) && (url.host != nil || scheme == "mailto")
    }

    private static func draft(_ kind: ItemKind, text: String?, image: CapturedImage?, reps: [Representation]) -> CaptureDraft {
        let primary = image?.data ?? Data((text ?? "").utf8)
        return CaptureDraft(kind: kind, contentHash: ContentHasher.itemHash(kind: kind, primary: primary),
                            text: text, image: image, representations: reps,
                            byteSize: primary.count + reps.reduce(0) { $0 + $1.data.count })
    }
}

public enum ContentHasher {
    public static func sha256Hex(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    /// Dedupe key: sha256(kind || 0x00 || primary content). Contract: items.content_hash.
    public static func itemHash(kind: ItemKind, primary: Data) -> String {
        var h = SHA256()
        h.update(data: Data(kind.rawValue.utf8))
        h.update(data: Data([0]))
        h.update(data: primary)
        return h.finalize().map { String(format: "%02x", $0) }.joined()
    }
}
