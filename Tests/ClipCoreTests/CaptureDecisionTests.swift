import Foundation
import Testing
@testable import ClipCore

@Suite struct CaptureDecisionTests {
    let ctx = CaptureContext(frontmostBundleID: "com.apple.Safari", frontmostName: "Safari", excludedBundleIDs: [], lastSelfWriteChangeCount: nil)

    // AC3.1 — privacy types are rejected before any content is read.
    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"])
    func concealedTypesSkipBeforeRead(type: String) {
        let pre = CaptureDecision.preflight(types: ["public.utf8-plain-text", type], changeCount: 5, context: ctx)
        #expect(pre == .skip(.concealed))
    }

    // AC3.2
    @Test func excludedAppSkips() {
        var c = ctx; c.excludedBundleIDs = ["com.apple.Safari"]
        #expect(CaptureDecision.preflight(types: ["public.utf8-plain-text"], changeCount: 5, context: c) == .skip(.excludedApp))
    }

    // AC3.3 / I6 — self writes are recognised by marker type or by change count.
    @Test func selfWriteSkips() {
        #expect(CaptureDecision.preflight(types: ["public.utf8-plain-text", SelfWriteMarker.type], changeCount: 5, context: ctx) == .skip(.selfWrite))
        var c = ctx; c.lastSelfWriteChangeCount = 5
        #expect(CaptureDecision.preflight(types: ["public.utf8-plain-text"], changeCount: 5, context: c) == .skip(.selfWrite))
        #expect(CaptureDecision.preflight(types: ["public.utf8-plain-text"], changeCount: 6, context: c) == .read)
    }

    @Test func emptyTypesSkip() {
        #expect(CaptureDecision.preflight(types: [], changeCount: 1, context: ctx) == .skip(.empty))
    }

    // AC1.4
    @Test(arguments: ["", "   ", "\n\t "])
    func blankTextSkips(s: String) {
        #expect(CaptureDecision.classify(textSnapshot(s)) == .skip(.empty))
    }

    // AC1.1 — classification precedence: file > rich > url > text > image.
    @Test func classifiesKinds() throws {
        let text = try #require(CaptureDecision.classify(textSnapshot("hello world")).draft)
        #expect(text.kind == .text && text.text == "hello world")

        let url = try #require(CaptureDecision.classify(textSnapshot("  https://example.com/a?b=1 ")).draft)
        #expect(url.kind == .url && url.text == "https://example.com/a?b=1")

        let notURL = try #require(CaptureDecision.classify(textSnapshot("see https://example.com now")).draft)
        #expect(notURL.kind == .text)

        var rich = textSnapshot("Bold")
        rich.types.append("public.rtf"); rich.rtf = Data("{\\rtf1 Bold}".utf8)
        let r = try #require(CaptureDecision.classify(rich).draft)
        #expect(r.kind == .rich && r.text == "Bold" && r.representations.map(\.uti) == ["public.rtf"])

        var file = textSnapshot("a.png")
        file.types.append("public.file-url"); file.fileURLs = ["file:///Users/x/a.png", "file:///Users/x/b.txt"]
        let f = try #require(CaptureDecision.classify(file).draft)
        #expect(f.kind == .file && f.text == "/Users/x/a.png\n/Users/x/b.txt")

        let img = PasteboardSnapshot(changeCount: 1, types: ["public.png"], image: CapturedImage(data: pngBytes(seed: 1), uti: "public.png", width: 10, height: 20))
        let i = try #require(CaptureDecision.classify(img).draft)
        #expect(i.kind == .image && i.text == nil && i.image?.width == 10)
    }

    @Test func unsupportedSkips() {
        let s = PasteboardSnapshot(changeCount: 1, types: ["com.example.private"])
        #expect(CaptureDecision.classify(s) == .skip(.unsupported))
    }

    // AC2.2 — the dedupe key includes the kind.
    @Test func hashIncludesKind() throws {
        let t = try #require(CaptureDecision.classify(textSnapshot("/Users/x/a.png")).draft)
        var file = textSnapshot("x"); file.types.append("public.file-url"); file.fileURLs = ["file:///Users/x/a.png"]
        let f = try #require(CaptureDecision.classify(file).draft)
        #expect(t.text == f.text)
        #expect(t.contentHash != f.contentHash)
        let t2 = try #require(CaptureDecision.classify(textSnapshot("/Users/x/a.png")).draft)
        #expect(t.contentHash == t2.contentHash)
    }
}
